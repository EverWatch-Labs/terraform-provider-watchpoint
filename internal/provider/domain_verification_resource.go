// A DNS domain verification (DomainVerificationController). Create-and-delete
// only: the API has no update for the domain, and the actual DNS check is a
// distinct action endpoint (.../{id}/verify) rather than a property. Every
// user-settable attribute therefore forces replacement. There is no GET-by-id;
// Read lists all domains and matches on id.

var (
	_ resource.Resource                = (*domainVerificationResource)(nil)
	_ resource.ResourceWithConfigure   = (*domainVerificationResource)(nil)
	_ resource.ResourceWithImportState = (*domainVerificationResource)(nil)
)

// NewDomainVerificationResource is the resource constructor wired into the provider.
func NewDomainVerificationResource() resource.Resource { return &domainVerificationResource{} }

type domainVerificationResource struct {
	client *client.Client
}

// domainVerificationModel maps schema attributes <-> Terraform state.
type domainVerificationModel struct {
	ID                types.String `tfsdk:"id"`
	Domain            types.String `tfsdk:"domain"`
	Verify            types.Bool   `tfsdk:"verify"`
	VerificationToken types.String `tfsdk:"verification_token"`
	TxtRecordValue    types.String `tfsdk:"txt_record_value"`
	Status            types.String `tfsdk:"status"`
	CreatedAt         types.String `tfsdk:"created_at"`
}

// --- Wire DTOs (camelCase JSON matching the Identity API) ---

type domainVerificationInitiateBody struct {
	Domain string `json:"domain"`
}

// domainVerificationResponse covers both the create (initiate) response and a
// single element of the list response. Fields absent on one shape stay zero.
type domainVerificationResponse struct {
	ID                string  `json:"id"`
	Domain            string  `json:"domain"`
	VerificationToken string  `json:"verificationToken"`
	TxtRecordValue    string  `json:"txtRecordValue"`
	Status            string  `json:"status"`
	CreatedAt         *string `json:"createdAt"`
}

func (r *domainVerificationResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_domain_verification"
}

func (r *domainVerificationResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.client = configureClient(req, &resp.Diagnostics)
}

func (r *domainVerificationResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A DNS domain verification. Creating it issues a TXT-record token; publish that " +
			"record and (optionally) trigger the verify check. The domain cannot be changed in place.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "Domain verification ID.",
				Computed:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"domain": schema.StringAttribute{
				MarkdownDescription: "Domain to verify (e.g. `example.com`).",
				Required:            true,
				PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace()},
			},
			"verify": schema.BoolAttribute{
				MarkdownDescription: "When true, the provider triggers the DNS verify check once immediately " +
					"after creation. Failures (e.g. DNS not yet propagated) are ignored. Defaults to `false`.",
				Optional:      true,
				Computed:      true,
				Default:       booldefault.StaticBool(false),
				PlanModifiers: []planmodifier.Bool{boolplanmodifier.RequiresReplace()},
			},
			"verification_token": schema.StringAttribute{
				MarkdownDescription: "Verification token generated by the API.",
				Computed:            true,
			},
			"txt_record_value": schema.StringAttribute{
				MarkdownDescription: "DNS TXT record value to publish for verification.",
				Computed:            true,
			},
			"status": schema.StringAttribute{
				MarkdownDescription: "Verification status (e.g. `Pending`, `Verified`).",
				Computed:            true,
			},
			"created_at": schema.StringAttribute{
				MarkdownDescription: "Creation timestamp (RFC 3339).",
				Computed:            true,
			},
		},
	}
}

// applyResponse copies API response fields into the model. created_at is
// preserved when the source (the initiate response) omits it.
func (m *domainVerificationModel) applyResponse(resp *domainVerificationResponse) {
	m.ID = types.StringValue(resp.ID)
	m.Domain = types.StringValue(resp.Domain)
	m.VerificationToken = types.StringValue(resp.VerificationToken)
	m.TxtRecordValue = types.StringValue(resp.TxtRecordValue)
	m.Status = types.StringValue(resp.Status)
	if resp.CreatedAt != nil {
		m.CreatedAt = types.StringValue(*resp.CreatedAt)
	}
}

func (r *domainVerificationResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan domainVerificationModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	var created domainVerificationResponse
	path := r.client.Tenantf("/identity", "/domains")
	body := &domainVerificationInitiateBody{Domain: plan.Domain.ValueString()}
	if err := r.client.Post(ctx, path, body, &created); err != nil {
		resp.Diagnostics.AddError("Error initiating domain verification", err.Error())
		return
	}

	// Optionally trigger the verify check once. DNS may not have propagated, so
	// ignore failures entirely - the status is reflected on the next Read.
	if plan.Verify.ValueBool() {
		verifyPath := r.client.Tenantf("/identity", "/domains/%s/verify", created.ID)
		_ = r.client.Post(ctx, verifyPath, nil, nil)
	}

	plan.applyResponse(&created)

	// Refresh from the list so status/created_at reflect any verify attempt.
	if found, err := r.findDomainByID(ctx, created.ID); err != nil {
		resp.Diagnostics.AddError("Error reading domain verification after create", err.Error())
		return
	} else if found != nil {
		plan.applyResponse(found)
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *domainVerificationResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state domainVerificationModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	found, err := r.findDomainByID(ctx, state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Error reading domain verification", err.Error())
		return
	}
	if found == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	state.applyResponse(found)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update is a passthrough: every user-settable attribute forces replacement.
func (r *domainVerificationResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan domainVerificationModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *domainVerificationResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state domainVerificationModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	path := r.client.Tenantf("/identity", "/domains/%s", state.ID.ValueString())
	if err := r.client.Delete(ctx, path); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Error deleting domain verification", err.Error())
	}
}

func (r *domainVerificationResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	importByID(ctx, req, resp)
}

// findDomainByID lists the tenant's domain verifications and returns the one
// matching id, or nil when not present. The list endpoint returns a bare array.
func (r *domainVerificationResource) findDomainByID(ctx context.Context, id string) (*domainVerificationResponse, error) {
	var list []domainVerificationResponse
	path := r.client.Tenantf("/identity", "/domains")
	if err := r.client.Get(ctx, path, nil, &list); err != nil {
		return nil, err
	}
	for i := range list {
		if list[i].ID == id {
			return &list[i], nil
		}
	}
	return nil, nil
}
